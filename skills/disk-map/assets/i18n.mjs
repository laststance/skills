/** Translate shared viewer/report labels without changing agent-authored text.
 * @example
 * translate('ja', 'clear'); // '質問対象を解除'
 */
export function translate(locale, key, vars = {}) {
  return (I18N[locale]?.[key] ?? I18N.en[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

/** Localize runtime reasons in the viewer and static report; unknown text stays intact.
 * @example
 * localizeReason('Not assessed yet.', 'ja'); // 'まだ評価されていません。'
 */
export function localizeReason(reason, locale) {
  if (locale !== 'ja' || !reason) return reason ?? '';
  if (JAPANESE_REASONS[reason]) return JAPANESE_REASONS[reason];
  // Compose known prefixes without translating paths or user-provided prose.
  if (reason.startsWith('Needs review: ')) {
    const detail = `${reason.slice(14).replace(/\.+$/, '')}.`;
    return '確認が必要：' + (JAPANESE_REASONS[detail] ?? detail.split('; ').map((part) => localizeReason(part.endsWith('.') ? part : `${part}.`, locale)).join(' '));
  }
  const open = /^(\d+) open file\(s\) or working folder\(s\) are inside this location\.$/.exec(reason);
  if (open) return `この領域内で${open[1]}件のファイルまたは作業フォルダが使用中です。`;
  const held = /^(\d+) open file\(s\) or working folder\(s\) inside: (.+)\.$/.exec(reason);
  if (held) return `この領域内で${held[1]}件が使用中です：${held[2].replaceAll(' holds ', ' が使用中: ').replaceAll('the folder itself', 'このフォルダ')}`;
  const descendant = /^Contains protected data at (.+) \(credentials, site data or a Git repository\)\.$/.exec(reason);
  if (descendant) return `内部の ${descendant[1]} に保護対象があるため、操作できません。`;
  const protectedKind = /^Protected: (.+)\.$/.exec(reason);
  if (protectedKind) {
    const labels = { credentials: '認証情報', settings: '設定', 'site data': 'サイトデータ', mail: 'メール', messages: 'メッセージ', 'browser data': 'ブラウザデータ', 'iCloud Drive': 'iCloud Drive', 'cloud files': 'クラウドファイル', accounts: 'アカウント', calendars: 'カレンダー', contacts: '連絡先', 'browser profile': 'ブラウザプロファイル', 'Docker data': 'Dockerデータ', 'Docker settings': 'Docker設定', Trash: 'ゴミ箱', 'agent settings': 'エージェント設定', 'agent credentials': 'エージェント認証情報' };
    if (labels[protectedKind[1]]) return labels[protectedKind[1]] + 'を保護しています。';
  }
  return reason;
}
