// Disposable fixtures for disk-map tests. Everything lives under a fresh
// temporary directory with its own synthetic home and Trash.
import fsp from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Session } from '../scripts/lib/session.mjs';
import { ensurePrivateDir, runFixed } from '../scripts/lib/util.mjs';

/** Write a file of `bytes` non-zero bytes, creating parent folders. */
export async function writeBytes(file, bytes) {
  await fsp.mkdir(path.dirname(file), { recursive: true });
  await fsp.writeFile(file, Buffer.alloc(bytes, 7));
}

/**
 * Create an isolated fixture: home with a Git project (.next ignored),
 * a review-only recording, protected state, and a separate Trash.
 *
 * @example
 * const fx = await makeFixture();
 * // ... test ...
 * await fx.cleanup();
 */
export async function makeFixture() {
  const base = await fsp.realpath(await fsp.mkdtemp(path.join(os.tmpdir(), 'disk-map-test-')));
  const home = path.join(base, 'home');
  const trash = path.join(base, 'trash');
  const state = path.join(base, 'state');
  await fsp.mkdir(trash, { recursive: true });
  await fsp.mkdir(state, { recursive: true });
  const project = path.join(home, 'work', 'shop');
  await writeBytes(path.join(project, 'src', 'index.js'), 200);
  await fsp.writeFile(path.join(project, '.gitignore'), '.next\nnode_modules\n');
  await runFixed('/usr/bin/git', ['-C', project, 'init', '-q']);
  await writeBytes(path.join(project, '.next', 'cache', 'webpack.pack'), 300_000);
  await writeBytes(path.join(project, '.next', 'server', 'page.js'), 40_000);
  await writeBytes(path.join(home, 'Movies', 'old-demo', 'take-1.mov'), 500_000);
  await writeBytes(path.join(home, '.ssh', 'id_test'), 100);
  await writeBytes(path.join(home, 'Library', 'Application Support', 'Google', 'Chrome', 'Default', 'Cookies'), 100);
  await writeBytes(path.join(home, 'Documents', '日本語の資料', 'メモ.txt'), 1000);
  return { base, home, trash, state, project, cleanup: () => fsp.rm(base, { recursive: true, force: true }) };
}

/**
 * Fixture adapter for read-only process probes: `ps` and `lsof` return the
 * given lines; `git` runs for real (read-only `check-ignore`); named tools
 * map to handlers so CLI recipes never touch real caches.
 */
export function fakeExec({ processes = [], openFiles = [], tools = {} } = {}) {
  return async (file, args, options) => {
    if (file === '/bin/ps') return { code: 0, stdout: processes.join('\n'), stderr: '', timedOut: false };
    if (file === '/usr/sbin/lsof') return { code: 0, stdout: openFiles.map((target) => `p1\nn${target}`).join('\n'), stderr: '', timedOut: false };
    if (file === '/usr/bin/git') return runFixed(file, args, options);
    if (tools[file]) return tools[file](args);
    return { code: 127, stdout: '', stderr: 'not found', timedOut: false, spawnError: 'ENOENT' };
  };
}

/** Build a Session over a fixture with injected probes; the scan is not started. */
export async function newSession(fx, extra = {}) {
  const runDir = path.join(fx.state, 'runs', `run-${Math.random().toString(16).slice(2)}`);
  await ensurePrivateDir(runDir);
  const session = new Session({ runDir, root: fx.home, home: fx.home, trashDir: fx.trash, stateDir: fx.state, skillDir: path.join(fx.base, 'skill'), fileNodeThreshold: 0, exec: fakeExec(), ...extra });
  session.touchAgent();
  return session;
}

export const VIEWER = { id: 'viewer-session-1' };
const now = () => new Date().toISOString();

/** A complete safe build-output assessment (local + documentation evidence). */
export function safeAssessment(candidateId, recipe = 'build-output') {
  return {
    candidateId, risk: 'safe', purpose: 'Next.js build output', reason: 'Regenerated by the next build.',
    consequences: ['The next build runs slower once.'],
    evidence: [{ kind: 'local', reference: 'git check-ignore reports the folder as ignored', checkedAt: now() }, { kind: 'documentation', reference: 'https://nextjs.org/docs/app/api-reference/cli/next', checkedAt: now() }],
    recipe, question: null,
  };
}

/** A review-required assessment with a user question. */
export function reviewAssessment(candidateId) {
  return { candidateId, risk: 'review', purpose: 'Old screen recordings', reason: 'Personal media; ownership is uncertain.', consequences: ['The recording is gone if the Trash is emptied.'], evidence: [{ kind: 'local', reference: 'Last modified long ago', checkedAt: now() }], recipe: 'trash', question: 'Do you still need these recordings?' };
}

/** Find the candidate/node ID for an absolute path in the current scan. */
export const idFor = (session, target) => session.scan.tree.idOf(session.scan.tree.findByPath(target));

/** Scan, then mark everything "safe"/"review" through the real assess path. */
export async function scannedSession(fx, extra) {
  const session = await newSession(fx, extra);
  await session.startScan();
  return session;
}
